    const copiedClosed=await service.transferTopic(owner,closedSource,targetId,true);
    assert.notEqual(copiedClosed,top,"closed source sessions remain available for later-session copies");
    assert.equal((await access.requireMeeting(owner,meetingId)).state,"closed");
    await assert.rejects(service.saveTopic(writer,top,topicValues,0,false),/abgeschlossen|weitergegeben/);
